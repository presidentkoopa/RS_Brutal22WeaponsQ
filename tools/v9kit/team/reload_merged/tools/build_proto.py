"""Builds the real-VR-reload prototype packs.

  build_proto.py bd <out.pk3> [--test]   from out/quick.pk3 (RS_BD22_Models v8 + hands)
  build_proto.py vp <out.pk3> [--test]   from vplus/RS_VanillaVRPlus_VR.pk3

Adds / replaces (team/reload/src, generated by gen_rsr.py and rsr_patch.py):
  zscript/rsr/vreload.zs, zscript/rsr/rsr_guns.zs   the reload (rsr_guns.<set>.zs)
  zscript/rsvr/vrhand.zs                            + OffDir (the off controller's axes)
  zscript/rsq/hands.zs                              + the four hooks (hands_hook.py)
  BD: actors/Weapons/Rifle.dec   V+: Decorate/rifle.txt   (rsr_patch.py)
  MODELDEF.rsr, CVARINFO.rsr, the clear skin; ZSCRIPT / MAPINFO / MENUDEF edits
--test: the fake VR hands + scripted off hand + logger (team/reload/rtest/vrhand_rsr.zs).
"""
import sys, os, json, zipfile, subprocess, shutil
sys.dont_write_bytecode = True
os.environ['PYTHONDONTWRITEBYTECODE'] = '1'

S = '/tmp/claude-0/-home-claude/688b1996-39a0-5234-911a-a90085ab177b/scratchpad'
R = S + '/team/reload'
SRC = R + '/src'
TOOLS = R + '/tools'

BASE = {'bd': S + '/out/quick.pk3', 'vp': S + '/vplus/RS_VanillaVRPlus_VR.pk3'}
ZS = {'bd': 'ZSCRIPT.rsvr', 'vp': 'ZSCRIPT.rsq'}
MI = {'bd': 'MAPINFO.rsvr', 'vp': 'MAPINFO.rsq'}


def menudef(t):
    # the old immersive reload's help (markers, paused steps) and its shells slider go
    lines = t.split('\n')
    a = [k for k, l in enumerate(lines) if 'StaticText "Immersive:' in l]
    b = [k for k, l in enumerate(lines) if 'to do a step for you.' in l]
    if len(a) != 1 or len(b) != 1 or b[0] < a[0]:
        raise SystemExit('MENUDEF: the old immersive help not found')
    end = b[0] + 1
    if lines[end].strip() == 'StaticText " "':
        end += 1
    del lines[a[0]:end]
    lines = [l for l in lines if 'rsq_shells' not in l]
    t = '\n'.join(lines)
    for bad in ('marker', 'Immersive:', 'vr_two_handed_weapons'):
        if bad in t:
            raise SystemExit('MENUDEF: still mentions %r' % bad)
    old = '\tOption "Reloading", "rsq_reload", "RSQ_ReloadMode"\n'
    if t.count(old) != 1:
        raise SystemExit('MENUDEF: Reloading item not found')
    t = t.replace(old,
        '\tRSRReload "Reloading", "rsq_reload", "RSQ_ReloadMode"\n'
        '\tStaticText " "\n'
        '\tStaticText "VR reloading: reload drops the magazine. Take", 1\n'
        '\tStaticText "a new one with the off-hand trigger, or with the", 1\n'
        '\tStaticText "off grip at least 50 cm from the gun (closer, the", 1\n'
        '\tStaticText "grip steadies the gun as usual). Put it under the", 1\n'
        '\tStaticText "well and push it home. When the gun needs it,", 1\n'
        '\tStaticText "take the handle or slide with the off trigger,", 1\n'
        '\tStaticText "pull it all the way back and let go.", 1\n')
    old2 = '\tOption "Reload debug readout", "rsq_debug", "OnOff"\n'
    if t.count(old2) == 1:
        t = t.replace(old2, old2 + '\tOption "Real reload: print key codes and steps", "rsr_debug", "OnOff"\n'
                                   '\tOption "Grab with the off-hand trigger", "rsr_grab_buttons", "RSR_GrabButtons"\n'
                                   '\tOption "Take magazines", "rsr_pouch", "RSR_Pouch"\n')
    t = t.replace('1, "Immersive (VR)"', '1, "VR"')
    t += ('\nOptionValue "RSR_GrabButtons"\n{\n\t0, "No (grip, 50 cm away only)"\n\t67108864, "Yes"\n}\n'
          '\nOptionValue "RSR_Pouch"\n{\n\t0, "Anywhere off the gun"\n\t1, "At the belt"\n}\n')
    return t


def main(kind, out, test):
    only = ['--only', sys.argv[sys.argv.index('--only') + 1]] if '--only' in sys.argv else []
    subprocess.check_call([sys.executable, '-I', TOOLS + '/gen_rsr.py', SRC] + only, stdout=subprocess.DEVNULL)
    subprocess.check_call([sys.executable, '-I', TOOLS + '/rsr_patch.py', SRC] + only, stdout=subprocess.DEVNULL)
    weapons = json.load(open(SRC + '/rsr_weapons.json'))[kind]
    files = json.load(open(SRC + '/rsr_files.json'))[kind]
    src = zipfile.ZipFile(BASE[kind])
    hands_in = R + '/_hands_in.zs'
    # the hands: the hands work's latest (team/hands.zs + team/gunmoves_<set>.zs) unless --v8hands
    team_hands = S + '/team/hands.zs'
    gunmoves = S + '/team/gunmoves_%s.zs' % {'bd': 'bd22', 'vp': 'vplus'}[kind]
    use_team = '--v8hands' not in sys.argv and os.path.exists(team_hands) and os.path.exists(gunmoves)
    if use_team:
        shutil.copy(team_hands, hands_in)
    else:
        open(hands_in, 'wb').write(src.read('zscript/rsq/hands.zs'))
    subprocess.check_call([sys.executable, TOOLS + '/hands_hook.py', hands_in, SRC + '/zscript/rsq/hands.zs'], stdout=subprocess.DEVNULL)
    if test:
        # TEST VIEW only: keep the hands with the gun when every layer is yawed (rsr_test_yaw)
        h = open(SRC + '/zscript/rsq/hands.zs').read()
        a = '\toverride Vector3, Vector3 ModifyBobLayer3D(Vector3 translation, Vector3 rotation, int layer, double ticfrac)\n\t{\n'
        if h.count(a) != 1:
            raise SystemExit('test hook anchor')
        h = h.replace(a, a + '\t\ttranslation += RSR_TestView.HandShift(layer);\t// TEST ONLY\n')
        open(R + '/_hands_test.zs', 'w').write(h)
    repl = {k: open(v, 'rb').read() for k, v in weapons.items()}
    repl.update({
        'zscript/rsq/hands.zs': open((R + '/_hands_test.zs') if test else (SRC + '/zscript/rsq/hands.zs'), 'rb').read(),
        'zscript/rsvr/vrhand.zs': open((R + '/rtest/vrhand_rsr.zs') if test else (SRC + '/zscript/rsvr/vrhand.zs'), 'rb').read(),
    })
    zs = src.read(ZS[kind]).decode()
    if use_team and 'zscript/rsq/gunmoves.zs' not in zs:
        a = '#include "zscript/rsq/hands.zs"'
        if zs.count(a) != 1:
            raise SystemExit('ZSCRIPT: hands include')
        zs = zs.replace(a, '#include "zscript/rsq/gunmoves.zs"\n' + a)
    zs += '\n// RS real VR reload (zscript/rsr, team/reload)\n#include "zscript/rsr/vreload.zs"\n#include "zscript/rsr/rsr_guns.zs"\n'
    repl[ZS[kind]] = zs.encode()
    mi = src.read(MI[kind]).decode()
    handlers = '"RSR_Handler", "RSR_TestDriver"' if test else '"RSR_Handler"'
    if mi.count('"RSQ_Ballistics"') != 1:
        raise SystemExit('MAPINFO: anchor')
    mi = mi.replace('"RSQ_Ballistics"', '"RSQ_Ballistics", ' + handlers)
    repl[MI[kind]] = mi.encode()
    repl['MENUDEF.rsq'] = menudef(src.read('MENUDEF.rsq').decode()).encode()
    add = {
        'zscript/rsr/vreload.zs': open(SRC + '/zscript/rsr/vreload.zs', 'rb').read(),
        'zscript/rsr/rsr_guns.zs': open(SRC + '/zscript/rsr/rsr_guns.%s.zs' % kind, 'rb').read(),
        'MODELDEF.rsr': open(SRC + '/MODELDEF.rsr.' + kind, 'rb').read() + open(SRC + '/MODELDEF.rsr.hands', 'rb').read(),
        'CVARINFO.rsr': open(SRC + '/CVARINFO.rsr', 'rb').read(),
    }
    # the clear skin in each gun's model folder, and any mesh with split surfaces (gen_rsr.py)
    add.update({k: open(v, 'rb').read() for k, v in files.items()})
    if use_team:
        add['zscript/rsq/gunmoves.zs'] = open(gunmoves, 'rb').read()
    if test:
        add['CVARINFO.rtest'] = (b'user int rsrtest_script = 1;\nuser bool rsr_test_offdraw = true;\nuser float rsr_test_yaw = 0;\nuser float rsrtest_magscale = 0;\n')
    tmp = out + '.tmp'
    z = zipfile.ZipFile(tmp, 'w')
    seen = set()
    for i in src.infolist():
        if i.filename in add:
            continue
        data = repl.get(i.filename)
        if data is not None:
            z.writestr(i.filename, data, compress_type=zipfile.ZIP_DEFLATED)
            seen.add(i.filename)
            continue
        # copy as it is (the meshes stay zip-LZMA: QZD reads method 14)
        z.writestr(i, src.read(i.filename), compress_type=i.compress_type)
    for k in repl:
        if k not in seen:
            raise SystemExit('base pack has no ' + k)
    for k, v in add.items():
        z.writestr(k, v, compress_type=zipfile.ZIP_DEFLATED)
    z.close()
    os.replace(tmp, out)
    print('built', out, os.path.getsize(out), 'bytes; hands:', 'team/hands.zs' if use_team else 'base pack', '; added/replaced', sorted(list(repl) + list(add)))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], '--test' in sys.argv)

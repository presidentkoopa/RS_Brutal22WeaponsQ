"""Generate the VR hands data for a pack from a fits file:
  <out>/zscript/rsq/handtable.zs   per-gun frames, hooks and support points
  <out>/MODELDEF.rsq               hand blocks (+ the debris blocks)
  <out>/models/rsq/hand.md3, hand2.md3, ammo/*   meshes cut to the frames used

  python rsq_hands_gen.py                                  BD22: hands/fits.json -> vrmelee/
  python rsq_hands_gen.py <fits.json> <out dir>            another set (Vanilla VR Plus:
                                                           vplus/vfits.json -> vplus/pk3)

The hands and their poses are Ermac's (Force Unleashed / Rusted Legacy, MIT):
hand.md3 holds a gun-hand pose per weapon, hand2.md3 a support-hand pose, both
drawn exactly as his weapons draw them (Scale -1 1 1, Offset 0 -24 -10).
hands/fitall.py moved each pose onto the set's gun (translation only, plus a
rotation for handles that run another way: the minigun's side handle, the
chainsaw's rear and top handles); the hook here is that move.
"""
import os, sys, json, io
import md3strip
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
V = os.path.join(HERE, 'vrmelee')
ERM = '/mnt/user-data/uploads/DOOMWork/_old/doom-force-unleashed_devbuild/models/'

# Ermac's sets: gun-hand frame (two hands), support frame, one-hand frame
SETS = {'pistol': (19, 4, 6), 'shotgun': (30, 15, 30), 'ssg': (47, 33, 47), 'chaingun': (84, 70, 84),
        'rocket': (95, 80, 95), 'plasma': (106, 91, 106), 'bfg': (113, 98, 113), 'chainsaw': (29, 14, 29)}

# what the free hand carries while reloading: state letter -> (ammo_hand frame, mesh, skin)
AMMO = {'B': (0, 'mag_pistol.md3', 'berettam9.jpg'),
        'C': (1, 'shot_shell.md3', 'shells.png'),
        'D': (2, 'shot_shell2.md3', 'shells.png'),
        'E': (3, 'mag_chaingun.md3', 'chaingun.png'),
        'F': (4, 'pod_rocket.md3', 'rocketlauncher.png'),
        'G': (5, 'mag_plasma.md3', 'plasmarifle.png')}

LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'


def hook_from_shift(d):
    f, l, u = d
    return (round(l, 2), round(u, 2), round(-f, 2))


def main(fits_path=None, out=None):
    global V
    if out:
        V = out
    fits = json.load(open(fits_path or os.path.join(HERE, 'hands', 'fits.json')))
    order = sorted(fits)
    gun_frames = sorted({SETS[fits[c]['gun_set']][0] for c in order} | {SETS[fits[c]['gun_set']][2] for c in order})
    sup_frames = sorted({SETS[fits[c]['sup_set']][1] for c in order})
    hand_keep = [0, 1] + [f for f in gun_frames if f not in (0, 1)]
    hand2_keep = sup_frames
    gl = {f: LETTERS[i] for i, f in enumerate(gun_frames)}
    sl = {f: LETTERS[i] for i, f in enumerate(sup_frames)}

    os.makedirs(os.path.join(V, 'models/rsq'), exist_ok=True)
    for name, keep in (('hand.md3', hand_keep), ('hand2.md3', hand2_keep)):
        d = open(ERM + 'hand/' + name, 'rb').read()
        new = md3strip.strip(d, keep)
        md3strip.verify(d, new, keep)
        open(os.path.join(V, 'models/rsq', name), 'wb').write(new)
    for L, (fr, mesh, skin) in AMMO.items():
        open(os.path.join(V, 'models/rsq', mesh), 'wb').write(open(ERM + 'ammo_hand/' + mesh, 'rb').read())
    open(os.path.join(V, 'models/rsq/ammo_hand.md3'), 'wb').write(open(ERM + 'ammo_hand/ammo_hand.md3', 'rb').read())
    for skin in sorted({a[2] for a in AMMO.values()}):
        src = ERM + 'ammo_hand/' + skin
        out = os.path.join(V, 'models/rsq', skin)
        im = Image.open(src)
        if im.size[0] > 256:     # the mags use a corner of a weapon's whole skin: 256 is plenty
            q = im.convert('RGB').resize((256, 256), Image.LANCZOS).quantize(colors=256)
            q.info.pop('transparency', None)
            q.save(out, optimize=True)
        else:
            open(out, 'wb').write(open(src, 'rb').read())
        print(skin, os.path.getsize(out))

    # ---------------- MODELDEF.rsq
    hidx = {f: i for i, f in enumerate(hand_keep)}
    h2idx = {f: i for i, f in enumerate(hand2_keep)}
    md = ['// RS VR hands (zscript/rsq/hands.zs). Hands and poses: Ermac, Force Unleashed /',
          '// Rusted Legacy (MIT, models/rsq/LICENSE_RustedLegacy_MIT.txt), drawn the way his',
          '// weapons draw them; generated by rsq_hands_gen.py from hands/fits.json.',
          '',
          '// the gun hand (main controller) and the support hand (main controller, on the gun)',
          'Model RSQ_GunSide', '{', '\tPath "models/rsq"', '\tModel 0 "hand.md3"', '\tSkin 0 "hand.png"',
          '\tScale -1.0 1.0 1.0', '\tOffset 0.0 -24.0 -10.0']
    md += ['\tFrameIndex RQGS %s 0 %d\t// Ermac hand.md3 frame %d' % (gl[f], hidx[f], f) for f in gun_frames]
    md += ['}', '', 'Model RSQ_GunSide', '{', '\tPath "models/rsq"', '\tModel 0 "hand2.md3"', '\tSkin 0 "hand.png"',
           '\tScale -1.0 1.0 1.0', '\tOffset 0.0 -24.0 -10.0']
    md += ['\tFrameIndex RQSP %s 0 %d\t// Ermac hand2.md3 frame %d' % (sl[f], h2idx[f], f) for f in sup_frames]
    md += ['}', '', '// the free hand (off controller): open, a fist, or holding ammo',
           'Model RSQ_Hands', '{', '\tPath "models/rsq"', '\tModel 0 "hand.md3"', '\tSkin 0 "hand.png"',
           '\tScale -1.0 1.0 1.0', '\tOffset 0.0 -24.0 -10.0',
           '\tFrameIndex RQHN A 0 %d' % hidx[0], '\tFrameIndex RQHN H 0 %d' % hidx[1], '}', '']
    for L, (fr, mesh, skin) in sorted(AMMO.items()):
        md += ['Model RSQ_Hands', '{', '\tPath "models/rsq"', '\tModel 0 "ammo_hand.md3"', '\tSkin 0 "hand.png"',
               '\tModel 1 "%s"' % mesh, '\tSkin 1 "%s"' % skin,
               '\tScale -1.0 1.0 1.0', '\tOffset 0.0 -24.0 -10.0',
               '\tFrameIndex RQHN %s 0 %d' % (L, fr), '\tFrameIndex RQHN %s 1 0' % L, '}', '']
    mdp = os.path.join(V, 'MODELDEF.rsq')
    old = open(mdp if os.path.exists(mdp) else os.path.join(HERE, 'vrmelee', 'MODELDEF.rsq')).read()
    deb = old[old.index('// debris'):]
    open(os.path.join(V, 'MODELDEF.rsq'), 'w').write('\n'.join(md) + '\n' + deb)

    # ---------------- handtable.zs
    rows = []
    for c in order:
        r = fits[c]
        gs, ss = SETS[r['gun_set']], SETS[r['sup_set']]
        if 'gun_hook' in r:      # a turned gun hand (the chainsaw's rear handle)
            gh, grot = r['gun_hook'], r['gun_rot']
        else:
            gh, grot = hook_from_shift(r['gun_shift']), (0, 0, 0)
        if 'sup_hook' in r:
            sh, rot = r['sup_hook'], r['sup_rot']
        else:
            sh, rot = hook_from_shift(r['sup_shift']), (0, 0, 0)
        t = [x / 100.0 for x in r['target']]
        rows.append((c, gl[gs[2]], gl[gs[0]], gh, sl[ss[1]], sh, rot, t, grot))
    zs = ['// generated by rsq_hands_gen.py from hands/fits.json -- do not edit by hand',
          '// Per gun: gun-hand frame (one hand, two hands), its hook and rotation, support frame, its hook',
          '// and rotation (ModifyBobLayer3D units), and where the support hand holds the gun',
          '// (metres in the gun hand\'s frame: forward, left, up).',
          '', 'class RSQ_HandTable abstract', '{',
          '\tclearscope static int Index(Weapon w)', '\t{', '\t\tif (!w)', '\t\t\treturn 0;']
    for i, row in enumerate(rows):
        zs.append('\t\tif (w is \'%s\')\treturn %d;' % (row[0], i + 1))
    zs += ['\t\treturn 0;', '\t}', '']

    def arr(name, vals, fmt):
        return '\t\tstatic const %s %s[] = { %s };' % ('int' if fmt == '%d' else 'double', name, ', '.join(fmt % v for v in vals))

    def frame_fn(name, vals):
        return ['\tclearscope static String %s(int i)' % name, '\t{',
                '\t\tstatic const String v[] = { "", %s };' % ', '.join('"%s"' % x for x in vals),
                '\t\treturn i > 0 && i < v.Size() ? v[i] : "";', '\t}', '']
    zs += frame_fn('GunOne', [r[1] for r in rows])
    zs += frame_fn('GunTwo', [r[2] for r in rows])
    zs += frame_fn('Support', [r[4] for r in rows])

    def vec_fn(name, vals):
        out = ['\tclearscope static Vector3 %s(int i)' % name, '\t{']
        for k, ax in enumerate('xyz'):
            out.append('\t\tstatic const double %s[] = { 0, %s };' % (ax, ', '.join('%.3f' % v[k] for v in vals)))
        out += ['\t\tif (i <= 0 || i >= x.Size())', '\t\t\treturn (0, 0, 0);', '\t\treturn (x[i], y[i], z[i]);', '\t}', '']
        return out
    zs += vec_fn('GunHook', [r[3] for r in rows])
    zs += vec_fn('GunRot', [r[8] for r in rows])
    zs += vec_fn('SupportHook', [r[5] for r in rows])
    zs += vec_fn('SupportRot', [r[6] for r in rows])
    zs += vec_fn('SupportPoint', [r[7] for r in rows])
    zs += ['}', '']
    open(os.path.join(V, 'zscript/rsq/handtable.zs'), 'w').write('\n'.join(zs))
    print('hand.md3 frames', hand_keep, 'hand2.md3 frames', hand2_keep)
    print('gun letters', gl, 'support letters', sl)


if __name__ == '__main__':
    main(*sys.argv[1:3])

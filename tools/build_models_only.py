#!/usr/bin/env python3
"""Pack ONLY the BD22 3D weapons: meshes, skins and MODELDEF. No code.

WHY THIS EXISTS SEPARATELY
--------------------------
The 3D weapon set and the hands/reload layer are two different products and
only one of them was asked for. This builds the weapon set on its own:

    models/bd/**        the meshes and their skins
    MODELDEF.bd.txt     generated by tools/gen_bd22_modeldef.py

and NOTHING ELSE. No zscript.txt, no ZScript, no CVARINFO, KEYCONF or MENUDEF,
no sprites. There is therefore no script in it that can abort the VM, and
nothing that can conflict with another mod's cvars or keys. A player drops it
in next to BD22 and gets 3D guns.

It needs BD22 loaded before it, because every block keys BD22's own classes and
sprites. An unknown class in a MODELDEF is fatal at startup, not a warning.

    python tools/build_models_only.py
    python tools/build_models_only.py -o <path>
"""

import argparse
import os
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_EXT = {".bak", ".md", ".py", ".ps1", ".txt~"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out",
                    default=os.path.join(os.path.dirname(ROOT), "RS_BD22_Models.pk3"))
    args = ap.parse_args()

    md = os.path.join(ROOT, "MODELDEF.bd.txt")
    if not os.path.exists(md):
        print("no MODELDEF.bd.txt -- run tools/gen_bd22_modeldef.py --write first")
        return 1

    # Every mesh/skin the modeldef actually names must be present, or the model
    # silently does not draw. Checked here rather than discovered in a headset.
    import re
    path_re = re.compile(r'^\s*Path\s+"?([^"\n]*)"?', re.I)
    file_re = re.compile(r'^\s*(?:Model|Skin|SurfaceSkin)\s+\d+\s+"([^"]+)"', re.I)

    cur, missing, wanted = None, [], 0
    for line in open(md, errors="replace"):
        m = path_re.match(line)
        if m:
            cur = m.group(1).replace("\\", "/").strip("/")
            continue
        m = file_re.match(line)
        if m and cur:
            wanted += 1
            rel = "%s/%s" % (cur, os.path.basename(m.group(1).replace("\\", "/")))
            if not os.path.exists(os.path.join(ROOT, rel)):
                missing.append(rel)

    if missing:
        print("MODELDEF names %d files that are not present:" % len(missing))
        for x in missing[:20]:
            print("   ", x)
        print("\nREFUSED.")
        return 1

    # NO SPRITES ARE SHIPPED. BD22 already provides the art for its own sprites,
    # which is what this MODELDEF keys, so there is nothing to fill in. An
    # earlier pass wrote blank placeholders here and three of them shadowed real
    # art -- FATBA0, PLAYA0 and USASP0 -- which would have made the player
    # sprite invisible. A rotation-0 lump overrides all eight rotations.
    fi_re = re.compile(r'^\s*FrameIndex\s+(\S+)\s+(\S+)', re.I)
    need = set()
    for line in open(md, errors="replace"):
        m = fi_re.match(line)
        if m and len(m.group(1)) == 4 and len(m.group(2)) == 1:
            need.add(("%s%s0" % (m.group(1), m.group(2))).upper())

    n = 0
    with zipfile.ZipFile(args.out, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(md, "MODELDEF.bd.txt")
        n += 1

        base = os.path.join(ROOT, "models", "bd")
        for dirpath, _dirs, files in os.walk(base):
            for fn in files:
                if os.path.splitext(fn)[1].lower() in SKIP_EXT:
                    continue
                full = os.path.join(dirpath, fn)
                z.write(full, os.path.relpath(full, ROOT).replace("\\", "/"))
                n += 1

    blocks = sum(1 for ln in open(md, errors="replace")
                 if ln.strip().lower().startswith("model ")
                 and len(ln.split()) == 2)
    print("%d guns, %d files referenced and all present" % (blocks, wanted))
    print("wrote %s" % args.out)
    print("%d entries, %.1f MB" % (n, os.path.getsize(args.out) / 1048576.0))
    print("\nLoad order: BD22 first, then this.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
